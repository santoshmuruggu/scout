"""LangGraph state machine for Scout: plan -> act -> cluster -> synthesize
-> critique -> END.

Day 4 note on why there's a cluster step the original 5-step sketch didn't
mention, and why verify() isn't its own graph node: verify() (see
verify.py) needs findings already grouped by identical claim, but two
independent articles agreeing "founded 2014" and "launched November 2014"
never share exact wording. Grouping is a semantic judgment call, so an
LLM does it (cluster_node) — and verify() runs as a plain function call
right after, still inside cluster_node, since the actual verified-vs-
flagged decision stays deterministic, domain-counting Python with
nothing for a graph node's retry/observability machinery to add. That
split keeps the one part of this pipeline that most needs to be
auditable free of model judgment.
"""

import sys
from datetime import datetime, timezone
from typing import TypedDict

from langchain_anthropic import ChatAnthropic
from langfuse import get_client
from langfuse.langchain import CallbackHandler
from langgraph.graph import END, StateGraph

from schema import (
    ClaimCluster,
    ClaimClusters,
    DueDiligenceReport,
    Fact,
    Finding,
    ReportNarrative,
)
from tools import with_retry
from tools.difc import lookup_difc_entity
from tools.search import news_search, web_search
from verify import verify

# Fixed categories a due-diligence pass should always touch. Sub-questions
# are generated by filling these templates with the company name rather
# than left to free-form planning, so every report covers the same ground
# and results stay comparable across the eval set.
SUB_QUESTION_TAXONOMY = [
    "Where is {company} legally registered, and under what license type "
    "(mainland DED, free zone, or DIFC)?",
    "Who are {company}'s founders, directors, or parent company?",
    "Has {company} raised funding, reported revenue, or shown other "
    "financial signals in public reporting?",
    "Where does {company} operate, and in what sector(s)?",
    "Is there any litigation, regulatory action, sanctions listing, or "
    "negative press associated with {company}?",
    "What has {company} done in the last 12 months (funding, "
    "partnerships, leadership changes, expansion)?",
]

# Index of the litigation/red-flag question — the one sub-question that
# gets a news search instead of a general web search, since regulatory
# action and negative press skew toward recent news coverage. Keeps the
# per-report search budget close to the ~5-10 calls this project is
# costed around instead of firing both search types on every question.
RED_FLAG_INDEX = 4

# One handler, reused across every LLM call. Langfuse's LangChain
# integration attaches each call to whatever trace is active on the
# OTel context at call time — that's what makes the three LLM calls
# below show up as child spans of one trace per company run, instead of
# three unrelated traces, once run() opens that trace context.
_langfuse_handler = CallbackHandler()


def _traced(step: str) -> dict:
    return {"callbacks": [_langfuse_handler], "run_name": f"scout:{step}"}


@with_retry
def _invoke_structured(structured_llm, prompt: str, step: str):
    # Reusing tools.with_retry here, not just for tool calls — the eval
    # run surfaced real structured-output flakiness on the Anthropic side
    # (a nested list field arriving as a JSON-encoded string once, a
    # truncated field another time). Same failure shape as a flaky tool
    # call, same fix: retry before giving up.
    return structured_llm.invoke(prompt, config=_traced(step))


def generate_sub_questions(company: str) -> list[str]:
    return [template.format(company=company) for template in SUB_QUESTION_TAXONOMY]


class ResearchState(TypedDict):
    company: str
    sub_questions: list[str]
    findings: list[Finding]  # raw, source-tagged
    verified: list[ClaimCluster]  # confirmed by 2+ independent domains
    flagged: list[ClaimCluster]  # single-source or conflicting
    report: DueDiligenceReport | None
    tool_calls: int  # total tool invocations attempted this run
    tool_errors: list[str]  # one entry per tool call that failed after retries


def plan_node(state: ResearchState) -> dict:
    return {"sub_questions": generate_sub_questions(state["company"])}


def act_node(state: ResearchState) -> dict:
    company = state["company"]
    findings: list[Finding] = []
    tool_calls = 0
    tool_errors: list[str] = []

    for i, question in enumerate(state["sub_questions"]):
        # A bare company name is often ambiguous (a common word, or a name
        # shared with an unrelated company) — "Beehive" alone pulls in
        # actual beekeeping articles and an unrelated "Hive Digital
        # Technologies" SEC filing. Quoting the name and anchoring it to
        # "UAE Dubai company" cuts that noise off at the source instead of
        # relying on later steps to filter it back out.
        query = f'"{company}" UAE Dubai company — {question}'
        search = news_search if i == RED_FLAG_INDEX else web_search
        tool_calls += 1
        try:
            findings.extend(search(query, max_results=4))
        except Exception as exc:
            # A dead tool call (retries already exhausted inside the tool
            # node) shouldn't take the whole report down with it — skip
            # this sub-question's findings and keep going.
            msg = f"{search.__name__} failed for {query!r}: {exc}"
            print(f"[act] {msg}", file=sys.stderr)
            tool_errors.append(msg)

    tool_calls += 1
    try:
        findings.extend(lookup_difc_entity(company))
    except Exception as exc:
        msg = f"DIFC/DFSA lookup failed for {company!r}: {exc}"
        print(f"[act] {msg}", file=sys.stderr)
        tool_errors.append(msg)

    return {"findings": findings, "tool_calls": tool_calls, "tool_errors": tool_errors}


def _findings_text(findings: list[Finding]) -> str:
    return "\n".join(
        f"- [{f.source_domain}] {f.claim} (source: {f.source_url})" for f in findings
    )


def cluster_node(state: ResearchState) -> dict:
    """Group raw findings into atomic claims, each tagged with every
    source URL that actually backs it. This is the semantic-judgment half
    of verification — the domain-counting decision itself happens next,
    in verify_node, without another model call.
    """
    findings = state["findings"]
    if not findings:
        return {"verified": [], "flagged": []}

    llm = ChatAnthropic(model="claude-sonnet-5", max_tokens=16000)
    structured_llm = llm.with_structured_output(ClaimClusters)

    prompt = (
        "Below are raw, source-tagged findings about a UAE company, "
        "pulled from web/news search and, where applicable, the DFSA "
        "public register.\n\n"
        f"Company: {state['company']}\n\n"
        f"Findings:\n{_findings_text(findings)}\n\n"
        "Group these into atomic claims. Two findings belong in the same "
        "cluster only if they assert the same underlying fact, even if "
        "worded differently (e.g. \"founded 2014\" and \"launched "
        "November 2014\" about the same company are the same claim). Do "
        "not merge claims just because they're about the same company — "
        "different facts stay in different clusters, even a fact "
        "mentioned by only one source.\n\n"
        "Rules:\n"
        "- Each cluster's source_urls must be exact URLs copied from the "
        "findings above — never invent one.\n"
        "- Only include a URL in a cluster if that specific finding "
        "actually supports that specific claim.\n"
        "- If two sources give conflicting values for the same fact "
        "(e.g. different funding amounts, different HQ cities), keep "
        "them as separate clusters rather than picking one — that "
        "conflict is exactly what should surface as unverified.\n"
        "- Don't drop single-source claims — include them as their own "
        "cluster; verification decides confidence later, not you.\n"
    )

    result = _invoke_structured(structured_llm, prompt, "cluster")
    verified, flagged = verify(result.clusters)
    return {"verified": verified, "flagged": flagged}


def synthesize_node(state: ResearchState) -> dict:
    company = state["company"]
    verified, flagged = state["verified"], state["flagged"]

    key_facts = [
        Fact(claim=c.claim, sources=c.source_urls, confidence="verified") for c in verified
    ] + [Fact(claim=c.claim, sources=c.source_urls, confidence="flagged") for c in flagged]

    if not key_facts:
        report = DueDiligenceReport(
            company=company,
            summary=f"No public information could be retrieved for {company}.",
            key_facts=[],
            red_flags=[],
            sources=[],
            generated_at=datetime.now(timezone.utc),
        )
        return {"report": report}

    evidence_text = "\n".join(
        f"- [{f.confidence}] {f.claim} (sources: {', '.join(str(u) for u in f.sources)})"
        for f in key_facts
    )

    llm = ChatAnthropic(model="claude-sonnet-5", max_tokens=16000)
    structured_llm = llm.with_structured_output(ReportNarrative)

    prompt = (
        f"Company: {company}\n\nVerified and flagged claims:\n{evidence_text}\n\n"
        "Write a short summary and a red_flags list from these claims "
        "only.\n\n"
        "Rules:\n"
        "- State verified claims as fact. For flagged claims, say so "
        'explicitly ("reported by a single source", "sources disagree") '
        "— never present a flagged claim with the same confidence as a "
        "verified one.\n"
        "- red_flags covers concrete negative findings only (litigation, "
        "fines, regulatory action, financial distress, conflicting "
        "claims that themselves raise doubt) — empty list if none, "
        "don't invent any.\n"
        "- Don't state anything not present in the claims above.\n"
    )

    narrative = _invoke_structured(structured_llm, prompt, "synthesize")
    sources = sorted({str(u) for f in key_facts for u in f.sources})

    report = DueDiligenceReport(
        company=company,
        summary=narrative.summary,
        key_facts=key_facts,
        red_flags=narrative.red_flags,
        sources=sources,
        generated_at=datetime.now(timezone.utc),
    )
    return {"report": report}


def critique_node(state: ResearchState) -> dict:
    """Self-check pass over the drafted narrative. key_facts/confidence
    are already deterministic (verify.py decided them, not a model), so
    this only reviews the free-text parts synthesize_node wrote — summary
    and red_flags — for claims stated more confidently than the evidence
    supports, or not actually present in the evidence at all.
    """
    report = state["report"]
    if report is None or not report.key_facts:
        return {}

    evidence_text = "\n".join(
        f"- [{f.confidence}] {f.claim} (sources: {', '.join(str(u) for u in f.sources)})"
        for f in report.key_facts
    )

    llm = ChatAnthropic(model="claude-sonnet-5", max_tokens=16000)
    structured_llm = llm.with_structured_output(ReportNarrative)

    # Render red_flags as an actual bulleted list, not str(list) — feeding
    # the model a Python repr like "['a', 'b']" led it to echo that same
    # repr back as a single string instead of a real list, which broke
    # the structured-output parse.
    red_flags_text = "\n".join(f"- {r}" for r in report.red_flags) or "(none)"

    prompt = (
        "Review this draft summary and red_flags against the evidence "
        "they're supposed to be based on. Fix anything that:\n"
        "- states a flagged (single-source/conflicting) claim as if it "
        "were verified\n"
        "- asserts something the evidence below doesn't actually "
        "support\n"
        "- omits a real red flag that the evidence does support\n\n"
        f"Evidence:\n{evidence_text}\n\n"
        f"Draft summary:\n{report.summary}\n\n"
        f"Draft red_flags:\n{red_flags_text}\n\n"
        "Return the corrected summary and red_flags as a list of strings "
        "— if nothing needs fixing, return them unchanged."
    )

    try:
        revised = _invoke_structured(structured_llm, prompt, "critique")
    except Exception as exc:
        # Critique is a refinement pass, not load-bearing — a bad model
        # response here shouldn't discard an otherwise-good report.
        print(f"[critique] failed, keeping pre-critique draft: {exc}", file=sys.stderr)
        return {}

    report.summary = revised.summary
    report.red_flags = revised.red_flags
    return {"report": report}


def build_graph():
    graph = StateGraph(ResearchState)
    graph.add_node("plan", plan_node)
    graph.add_node("act", act_node)
    graph.add_node("cluster", cluster_node)
    graph.add_node("synthesize", synthesize_node)
    graph.add_node("critique", critique_node)
    graph.set_entry_point("plan")
    graph.add_edge("plan", "act")
    graph.add_edge("act", "cluster")
    graph.add_edge("cluster", "synthesize")
    graph.add_edge("synthesize", "critique")
    graph.add_edge("critique", END)
    return graph.compile()


def run_state(company: str) -> ResearchState:
    """Run the full pipeline and return the final state — findings,
    verified/flagged clusters, tool-call reliability data, and the
    report. Used by the eval harness, which needs more than just the
    report. run() below is the thin wrapper for normal callers.
    """
    app = build_graph()
    langfuse = get_client()
    # No separate "trace" type in this SDK — the root-most observation of
    # a tree *is* the trace. "agent" is the closest semantic fit for
    # "the whole plan-act-verify-synthesize-critique run."
    with langfuse.start_as_current_observation(
        as_type="agent", name=f"scout-research: {company}"
    ):
        result = app.invoke(
            {
                "company": company,
                "sub_questions": [],
                "findings": [],
                "verified": [],
                "flagged": [],
                "report": None,
                "tool_calls": 0,
                "tool_errors": [],
            }
        )
        report = result["report"]
        langfuse.set_current_trace_io(
            input={"company": company},
            output={"key_facts": len(report.key_facts)} if report else {},
        )
    langfuse.flush()
    return result


def run(company: str) -> DueDiligenceReport:
    return run_state(company)["report"]


if __name__ == "__main__":
    name = " ".join(sys.argv[1:]) or "Beehive"
    print(run(name).model_dump_json(indent=2))
